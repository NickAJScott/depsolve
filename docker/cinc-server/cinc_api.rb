# frozen_string_literal: true

# Talks to the CINC Server in this container as the pivotal superuser.
#
#   cinc_api.rb load ORG  < problem.json   upload every cookbook version in the problem
#   cinc_api.rb solve ORG < problem.json   ask the server to depsolve the problem's run list
#
# Cookbook versions are uploaded as metadata only (name, version, dependencies). That
# is everything the depsolver reads; there are no recipes or files.

require 'chef'
require 'json'

command, org = ARGV
abort 'usage: cinc_api.rb load|solve ORG < problem.json' unless %w[load solve].include?(command) && org

Chef::Config[:ssl_verify_mode] = :verify_none
Chef::Log.level = :fatal

def api(org)
  Chef::ServerAPI.new("https://localhost/organizations/#{org}",
                      client_name: 'pivotal',
                      signing_key_filename: '/etc/cinc-project/pivotal.pem')
end

def cookbook_body(name, version, dependencies)
  {
    'name' => "#{name}-#{version}",
    'cookbook_name' => name,
    'version' => version,
    'json_class' => 'Chef::CookbookVersion',
    'chef_type' => 'cookbook_version',
    'frozen?' => false,
    'metadata' => {
      'name' => name,
      'version' => version,
      'description' => 'generated by depsolve',
      'long_description' => '',
      'maintainer' => 'depsolve',
      'maintainer_email' => 'depsolve@example.invalid',
      'license' => 'Apache-2.0',
      'platforms' => {},
      'dependencies' => dependencies.transform_values { |raw| raw.strip.empty? ? '>= 0.0.0' : raw },
      'providing' => {},
      'recipes' => {}
    }
  }
end

problem = JSON.parse($stdin.read)

case command
when 'load'
  # The first version of a cookbook creates the cookbook record, and concurrent creates
  # of the same cookbook collide. Upload one version of each serially, the rest in parallel.
  jobs = Queue.new
  failures = Queue.new
  total = 0
  first = api(org)
  problem['cookbooks'].each do |name, versions|
    versions.each_with_index do |(version, dependencies), index|
      total += 1
      if index.zero?
        begin
          first.put("cookbooks/#{name}/#{version}", cookbook_body(name, version, dependencies))
        rescue StandardError => e
          failures << "#{name} #{version}: #{e.class}: #{e.message}"
        end
      else
        jobs << [name, version, dependencies]
      end
    end
  end
  workers = Array.new(8) do
    Thread.new do
      client = api(org)
      loop do
        name, version, dependencies = begin
          jobs.pop(true)
        rescue ThreadError
          break
        end
        begin
          client.put("cookbooks/#{name}/#{version}", cookbook_body(name, version, dependencies))
        rescue StandardError => e
          failures << "#{name} #{version}: #{e.class}: #{e.message}"
        end
      end
    end
  end
  workers.each(&:join)
  failed = Array.new(failures.size) { failures.pop }
  puts JSON.generate('uploaded' => total - failed.size, 'failed' => failed.size, 'first_failures' => failed.first(3))
  exit(failed.empty? ? 0 : 1)
when 'solve'
  run_list = problem['run_list'].map do |name, raw|
    case raw.strip
    when '' then name
    when /\A=?\s*(\d+\.\d+(\.\d+)?)\z/ then "#{name}@#{Regexp.last_match(1)}"
    else abort "a server run list can only pin an exact version, not #{name} #{raw.inspect}"
    end
  end
  start = Process.clock_gettime(Process::CLOCK_MONOTONIC)
  result = begin
    solved = api(org).post('environments/_default/cookbook_versions', 'run_list' => run_list)
    { 'status' => 'ok', 'http' => 200, 'solution' => solved.transform_values { |cookbook| cookbook['version'] } }
  rescue Net::HTTPClientException, Net::HTTPFatalError => e
    { 'status' => 'failed', 'http' => e.response.code.to_i, 'body' => e.response.body.to_s[0, 2000] }
  end
  result['seconds'] = Process.clock_gettime(Process::CLOCK_MONOTONIC) - start
  puts JSON.generate(result)
end
